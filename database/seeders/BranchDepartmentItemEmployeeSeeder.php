    // ─────────────────────────────────────────────────────────────
    //  فرع غزة
    // ─────────────────────────────────────────────────────────────
    private function resolveGazaBranch(): Branch
    {
        $branch = Branch::query()
            ->where('code', 'GAZA-01')
            ->orWhere('name', 'like', '%غزة%')
            ->first();

        if (! $branch) {
            $branch = Branch::create([
                'name' => 'فرع غزة الرئيسي',
                'code' => 'GAZA-01',
                'address' => 'غزة',
                'phone' => null,
                'is_active' => true,
                'isMainBranch' => false,
                'openingTime' => '08:00:00',
                'closingTime' => '23:59:00',
            ]);
        }

        return $branch;
    }

    // ─────────────────────────────────────────────────────────────
    //  الأقسام (31) — حسب code (فريد) مع ربط parent عبر code
    // ─────────────────────────────────────────────────────────────
    private function seedDepartments(): array
    {
        $map = []; // origId => new department id

        foreach ($this->departmentBlueprint() as $origId => $data) {
            $parentId = is_null($data['parent']) ? null : ($map[$data['parent']] ?? null);

            $dept = Department::updateOrCreate(
                ['code' => $data['code']],
                [
                    'name' => $data['name'],
                    'nameAr' => $data['nameAr'] ?? $data['name'],
                    'type' => $data['type'],
                    'parent_id' => $parentId,
                    'shortName' => $data['shortName'] ?? null,
                    'color' => $data['color'] ?? '#ef4444',
                    'status' => 'ACTIVE',
                    'is_active' => true,
                    'is_central' => false,
                    'hasKds' => $data['hasKds'] ?? false,
                    'autoPrintTicket' => $data['autoPrintTicket'] ?? false,
                    'stationNumber' => $data['stationNumber'] ?? null,
                    'defaultPrepTime' => $data['defaultPrepTime'] ?? 0,
                    'maxConcurrentOrders' => $data['maxConcurrentOrders'] ?? 10,
                    'start_code' => '100',
                ]
            );

            $map[$origId] = $dept->id;
        }

        return $map;
    }

    // ─────────────────────────────────────────────────────────────
    //  الأصناف (264) — حسب code (فريد)
    // ─────────────────────────────────────────────────────────────
    private function seedItems(array $deptMap): array
    {
        $map = []; // itemId => code

        foreach ($this->itemBlueprint() as [$origDept, $code, $name, $nameAr, $unit]) {
            $departmentId = $deptMap[$origDept] ?? null;
            if (! $departmentId) {
                $this->command?->warn("تخطّي الصنف {$nameAr} — القسم الأصلي #{$origDept} غير موجود");
                continue;
            }

            $item = Item::updateOrCreate(
                ['code' => (string) $code],
                [
                    'department_id' => $departmentId,
                    'name' => $name,
                    'name_ar' => $nameAr,
                    'unit' => $unit,
                    'is_active' => true,
                ]
            );

            $map[$item->id] = (string) $code;
        }

        return $map;
    }

    // ─────────────────────────────────────────────────────────────
    //  الربط بفرع غزة فقط
    // ─────────────────────────────────────────────────────────────
    private function linkToGaza(Branch $gaza, array $deptMap, array $itemCodeMap): void
    {
        $deptPivot = [];
        foreach (array_values($deptMap) as $deptId) {
            $deptPivot[$deptId] = ['is_active' => true];
        }
        $gaza->departments()->syncWithoutDetaching($deptPivot);

        $prices = $this->itemPrices(); // code => price
        $itemPivot = [];
        foreach ($itemCodeMap as $itemId => $code) {
            $itemPivot[$itemId] = [
                'price' => $prices[$code] ?? null,
                'is_active' => true,
            ];
        }
        $gaza->items()->syncWithoutDetaching($itemPivot);
    }

