    /**
     * استيراد فهارس الزبائن / الموردين / الموظفين القديمة (ملفات إكسل 2026-09)
     * إلى جداول customers / suppliers / employees.
     *
     * المصدر يحتوي فقط على (الرقم، الاسم) لكل سجل — باقي الحقول تُترك
     * فارغة/افتراضية ليتم استكمالها لاحقاً من واجهة النظام.
     * رقم الفهرس الأصلي يُحفظ في code/employeeId وفي meta/notes للتتبع.
     *
     * آمن للتشغيل المتكرر (updateOrCreate حسب code/employeeId).
     */
    public function run(): void
    {
        DB::transaction(function () {
            $this->seedCustomers();
            $this->seedSuppliers();
            $this->seedEmployees();
        });

        $this->command?->info('✅ Seeded legacy directory: '
            . count($this->customerBlueprint()) . ' عملاء، '
            . count($this->supplierBlueprint()) . ' موردين، '
            . count($this->employeeBlueprint()) . ' موظفين.');
    }

    // ─────────────────────────────────────────────────────────────
    //  العملاء — من فهرس زباين 992026.xlsx
    //  ملاحظة: يتحقق بالاسم أولاً لتفادي التكرار — هذه القائمة مستوردة
    //  يدوياً بالفعل لدى غالبية الزبائن عبر شاشة العملاء (code بصيغة CUS-xxxx).
    //  لا نلمس السجلات الموجودة إطلاقاً، فقط ننشئ الناقص منها.
    // ─────────────────────────────────────────────────────────────
    private function seedCustomers(): void
    {
        $existingNames = Customer::withTrashed()->pluck('name')
            ->map(fn ($n) => trim($n))
            ->flip();

        foreach ($this->customerBlueprint() as $legacyId => $name) {
            if (isset($existingNames[trim($name)])) {
                continue; // موجود مسبقاً بأي كود — لا نكرره
            }

            $code = 'CUST-' . str_pad((string) $legacyId, 4, '0', STR_PAD_LEFT);

            Customer::firstOrCreate(
                ['code' => $code],
                [
                    'name' => $name,
                    'status' => 'active',
                    'credit_limit' => 0,
                    'meta' => [
                        'legacy_index' => $legacyId,
                        'source' => 'فهرس زباين 992026.xlsx',
                    ],
                ]
            );
        }
    }

    // ─────────────────────────────────────────────────────────────
    //  الموردون — من فهرس موردين 992026.xlsx
    //  يتحقق بالاسم أولاً لتفادي التكرار، وإن وجد بنفس كود SUP-xxxx
    //  المتوقع يكتفي بإضافة ملاحظات/بيانات وصفية دون لمس بقية الحقول.
    // ─────────────────────────────────────────────────────────────
    private function seedSuppliers(): void
    {
        $existingNames = Supplier::withTrashed()->pluck('name')
            ->map(fn ($n) => trim($n))
            ->flip();

        foreach ($this->supplierBlueprint() as $legacyId => $name) {
            if (isset($existingNames[trim($name)])) {
                continue; // موجود مسبقاً بأي كود — لا نكرره
            }

            $code = 'SUP-' . str_pad((string) $legacyId, 4, '0', STR_PAD_LEFT);

            Supplier::firstOrCreate(
                ['code' => $code],
                [
                    'name' => $name,
                    'status' => 'active',
                    'currency' => 'ILS',
                    'credit_limit' => 0,
                    'opening_balance' => 0,
                    'notes' => "مستورد من الفهرس القديم - رقم: {$legacyId}",
                    'meta' => [
                        'legacy_index' => $legacyId,
                        'source' => 'فهرس موردين 992026.xlsx',
                    ],
                ]
            );
        }
    }

    // ─────────────────────────────────────────────────────────────
    //  الموظفون — من فهرس موظفين 992026.xlsx
    //  ملاحظة: المصدر يحوي أسماء فقط بدون هاتف/تاريخ تعيين، وهما حقلان
    //  إلزاميان في جدول employees، لذا تُترك بقيم مؤقتة فارغة/تاريخ اليوم
    //  فقط للموظفين الجدد الفعليين. يتحقق بالاسم أولاً لتفادي التكرار —
    //  هذه القائمة موجودة بالفعل لدى غالبية الموظفين في جدول employees.
    // ─────────────────────────────────────────────────────────────
    private function seedEmployees(): void
    {
        $existingNames = Employee::withTrashed()->pluck('name')
            ->map(fn ($n) => trim($n))
            ->flip();

        foreach ($this->employeeBlueprint() as $legacyId => $name) {
            if (isset($existingNames[trim($name)])) {
                continue; // موجود مسبقاً بأي employeeId — لا نكرره
            }

            $employeeId = 'EMP-' . str_pad((string) $legacyId, 4, '0', STR_PAD_LEFT);

            Employee::firstOrCreate(
                ['employeeId' => $employeeId],
                [
                    'name' => $name,
                    'phone' => '',
                    'hireDate' => now(),
                    'role' => 'EMPLOYEE',
                    'status' => 'ACTIVE',
                    'notes' => "مستورد من الفهرس القديم - رقم: {$legacyId}",
                ]
            );
        }
    }

